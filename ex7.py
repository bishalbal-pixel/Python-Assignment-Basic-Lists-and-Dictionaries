languages = ["Python", "Java", "C", "JavaScript", "C++"]

# 1. Print each language
for lang in languages:
    print(lang)

# 2. Print each language with "I am learning..."
for lang in languages:
    print("I am learning", lang)

# 3. Print the number of characters in each language
for lang in languages:
    print(lang, "-", len(lang), "characters")