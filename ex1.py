# Create the list
fruits = ["Apple", "Banana", "Mango", "Orange", "Grapes"]

# 1. Print the complete list
print(fruits)

# 2. Print the first fruit
print(fruits[0])

# 3. Print the last fruit
print(fruits[-1])

# 4. Print the second and third fruits
print(fruits[1:3])

# 5. Print the number of fruits
print(len(fruits))